<?php

namespace App\Enums;

enum DriverStatusEnum: string
{
    /*
    |--------------------------------------------------------------------------
    | Le livreur n'est pas disponible.
    |--------------------------------------------------------------------------
    */
    case OFFLINE = 'offline';

    /*
    |--------------------------------------------------------------------------
    | Le livreur est disponible pour recevoir une mission.
    |--------------------------------------------------------------------------
    */
    case ONLINE = 'online';

    /*
    |--------------------------------------------------------------------------
    | Le livreur possède actuellement une livraison active.
    |--------------------------------------------------------------------------
    */
    case BUSY = 'busy';

    /*
    |--------------------------------------------------------------------------
    | Le compte du livreur est temporairement suspendu.
    |--------------------------------------------------------------------------
    */
    case SUSPENDED = 'suspended';
}